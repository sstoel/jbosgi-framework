package org.jboss.osgi.framework.internal;

import java.io.IOException;
import java.io.PrintWriter;
import java.lang.module.ModuleDescriptor;
import java.lang.module.ModuleFinder;
import java.lang.module.ModuleReader;
import java.lang.module.ModuleReference;
import java.lang.reflect.Constructor;
import java.lang.reflect.Executable;
import java.lang.reflect.Field;
import java.lang.reflect.GenericArrayType;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.lang.reflect.ParameterizedType;
import java.lang.reflect.Type;
import java.lang.reflect.TypeVariable;
import java.lang.reflect.WildcardType;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.HashSet;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.stream.Stream;

/**
 * Generates the uses directives of the platform packages of a Java release (3.9.5): for every package that a java.*
 * module exports to all modules, the other platform packages that the public API of the package refers to. The java.*
 * packages are not listed, they always come from the boot class path.
 *
 * Run it on the Java release that it describes, e.g.
 * <pre>
 * java -cp core/target/test-classes org.jboss.osgi.framework.internal.SystemPackagesUsesGenerator \
 *     core/src/main/resources/org/jboss/osgi/framework/internal/system-packages-uses-25.properties
 * </pre>
 */
public final class SystemPackagesUsesGenerator {

    public static void main(String[] args) throws IOException {
        if (args.length != 1)
            throw new IllegalArgumentException("Usage: SystemPackagesUsesGenerator <output file>");

        // The platform packages: the unqualified exports of the java.* modules
        Map<String, ModuleReference> packages = new TreeMap<String, ModuleReference>();
        for (ModuleReference ref : ModuleFinder.ofSystem().findAll()) {
            ModuleDescriptor descriptor = ref.descriptor();
            if (descriptor.name().startsWith("java.") == false)
                continue;
            for (ModuleDescriptor.Exports exports : descriptor.exports()) {
                if (exports.isQualified() == false)
                    packages.put(exports.source(), ref);
            }
        }

        Map<String, Set<String>> uses = new TreeMap<String, Set<String>>();
        for (Map.Entry<String, ModuleReference> entry : packages.entrySet()) {
            String packageName = entry.getKey();
            if (packageName.startsWith("java."))
                continue;
            Set<String> referenced = new TreeSet<String>();
            for (Class<?> clazz : getClasses(entry.getValue(), packageName)) {
                if (isApi(clazz))
                    addApiReferences(clazz, referenced);
            }
            referenced.remove(packageName);
            referenced.retainAll(packages.keySet());
            referenced.removeIf(name -> name.startsWith("java."));
            if (referenced.isEmpty() == false)
                uses.put(packageName, referenced);
        }

        Path output = Paths.get(args[0]);
        Files.createDirectories(output.toAbsolutePath().getParent());
        try (PrintWriter writer = new PrintWriter(Files.newBufferedWriter(output, StandardCharsets.UTF_8))) {
            writer.println("# The uses directives of the platform packages of Java " + Runtime.version().feature());
            writer.println("# Generated by " + SystemPackagesUsesGenerator.class.getName() + " on " + System.getProperty("java.vm.name") + " "
                    + System.getProperty("java.runtime.version"));
            for (Map.Entry<String, Set<String>> entry : uses.entrySet())
                writer.println(entry.getKey() + "=" + String.join(",", entry.getValue()));
        }
        System.out.println(uses.size() + " packages with uses written to " + output);
    }

    private static Set<Class<?>> getClasses(ModuleReference ref, String packageName) throws IOException {
        Set<Class<?>> result = new HashSet<Class<?>>();
        String path = packageName.replace('.', '/') + "/";
        try (ModuleReader reader = ref.open(); Stream<String> resources = reader.list()) {
            for (String resource : (Iterable<String>) resources::iterator) {
                if (resource.startsWith(path) && resource.endsWith(".class") && resource.indexOf('/', path.length()) < 0
                        && resource.endsWith("module-info.class") == false && resource.endsWith("package-info.class") == false) {
                    String className = resource.substring(0, resource.length() - 6).replace('/', '.');
                    try {
                        result.add(Class.forName(className, false, ClassLoader.getPlatformClassLoader()));
                    } catch (ClassNotFoundException | LinkageError ex) {
                        System.err.println("Skipping " + className + ": " + ex);
                    }
                }
            }
        }
        return result;
    }

    // A public class, or a public or protected member class of an API class
    private static boolean isApi(Class<?> clazz) {
        int modifiers = clazz.getModifiers();
        if (clazz.isAnonymousClass() || clazz.isLocalClass() || clazz.isSynthetic())
            return false;
        Class<?> enclosing = clazz.getDeclaringClass();
        if (enclosing == null)
            return Modifier.isPublic(modifiers);
        return (Modifier.isPublic(modifiers) || Modifier.isProtected(modifiers)) && isApi(enclosing);
    }

    private static void addApiReferences(Class<?> clazz, Set<String> referenced) {
        Set<Type> visited = new HashSet<Type>();
        addType(clazz.getGenericSuperclass(), clazz.getSuperclass(), referenced, visited);
        Type[] interfaces = genericOrRaw(clazz.getGenericInterfaces(), clazz.getInterfaces());
        for (Type type : interfaces)
            addType(type, null, referenced, visited);
        for (TypeVariable<?> variable : clazz.getTypeParameters())
            addType(variable, null, referenced, visited);
        for (Field field : clazz.getDeclaredFields()) {
            if (isApiMember(field.getModifiers()))
                addType(genericOrRaw(field), field.getType(), referenced, visited);
        }
        for (Constructor<?> constructor : clazz.getDeclaredConstructors()) {
            if (isApiMember(constructor.getModifiers()))
                addExecutable(constructor, referenced, visited);
        }
        for (Method method : clazz.getDeclaredMethods()) {
            if (isApiMember(method.getModifiers()) && method.isSynthetic() == false) {
                addExecutable(method, referenced, visited);
                addType(genericOrRaw(method), method.getReturnType(), referenced, visited);
            }
        }
    }

    private static boolean isApiMember(int modifiers) {
        return Modifier.isPublic(modifiers) || Modifier.isProtected(modifiers);
    }

    private static void addExecutable(Executable executable, Set<String> referenced, Set<Type> visited) {
        for (Type type : genericOrRaw(safeGenericParameterTypes(executable), executable.getParameterTypes()))
            addType(type, null, referenced, visited);
        for (Type type : genericOrRaw(safeGenericExceptionTypes(executable), executable.getExceptionTypes()))
            addType(type, null, referenced, visited);
        for (TypeVariable<?> variable : executable.getTypeParameters())
            addType(variable, null, referenced, visited);
    }

    private static Type[] safeGenericParameterTypes(Executable executable) {
        try {
            return executable.getGenericParameterTypes();
        } catch (RuntimeException | LinkageError ex) {
            return null;
        }
    }

    private static Type[] safeGenericExceptionTypes(Executable executable) {
        try {
            return executable.getGenericExceptionTypes();
        } catch (RuntimeException | LinkageError ex) {
            return null;
        }
    }

    private static Type genericOrRaw(Field field) {
        try {
            return field.getGenericType();
        } catch (RuntimeException | LinkageError ex) {
            return field.getType();
        }
    }

    private static Type genericOrRaw(Method method) {
        try {
            return method.getGenericReturnType();
        } catch (RuntimeException | LinkageError ex) {
            return method.getReturnType();
        }
    }

    private static Type[] genericOrRaw(Type[] generic, Class<?>[] raw) {
        return generic != null && generic.length == raw.length ? generic : raw;
    }

    private static void addType(Type type, Class<?> raw, Set<String> referenced, Set<Type> visited) {
        if (type == null)
            type = raw;
        if (type == null || visited.add(type) == false)
            return;
        if (type instanceof Class) {
            Class<?> clazz = (Class<?>) type;
            while (clazz.isArray())
                clazz = clazz.getComponentType();
            if (clazz.isPrimitive() == false)
                referenced.add(clazz.getPackageName());
        } else if (type instanceof ParameterizedType) {
            ParameterizedType parameterized = (ParameterizedType) type;
            addType(parameterized.getRawType(), null, referenced, visited);
            addType(parameterized.getOwnerType(), null, referenced, visited);
            for (Type argument : parameterized.getActualTypeArguments())
                addType(argument, null, referenced, visited);
        } else if (type instanceof GenericArrayType) {
            addType(((GenericArrayType) type).getGenericComponentType(), null, referenced, visited);
        } else if (type instanceof WildcardType) {
            for (Type bound : ((WildcardType) type).getUpperBounds())
                addType(bound, null, referenced, visited);
            for (Type bound : ((WildcardType) type).getLowerBounds())
                addType(bound, null, referenced, visited);
        } else if (type instanceof TypeVariable) {
            for (Type bound : ((TypeVariable<?>) type).getBounds())
                addType(bound, null, referenced, visited);
        }
    }
}
